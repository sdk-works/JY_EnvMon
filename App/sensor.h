/**
  ******************************************************************************
  * @file    sensor.h
  * @brief   传感器采集层：百叶箱(08) + 土壤三合一(18)
  *          所有采集通过 485-1 (BUS_SENSOR) 走Modbus-RTU
  ******************************************************************************
  */
#ifndef __SENSOR_H
#define __SENSOR_H

#include "app_def.h"

/* 分层采集（三种节拍彼此独立）：
 *   Fast = 百叶箱(0x08) 一次读 8 个寄存器：空气温湿度 / CO2 / 光照 / 气压。
 *          【为什么气压跟着快档】气压(0x01F9)与光照(0x01FA/0x01FB)在同一个
 *          连续寄存器块里，读光照必然把气压一起读回来；若把气压单独拆到 30s，
 *          就要多一次 Modbus 事务，反而增加总线轮询，与本意相反。故一并按 5s 采集。
 *   Slow = 土壤三合一(0x12)：土壤温湿度 / EC，30s 一次，减少慢变变量的总线轮询。
 * 两组各自只在成功时置对应 valid 位，失败清 0（契约：无效≠0）。 */
void Sensor_CollectFast(void);
void Sensor_CollectSlow(void);

/* 兼容接口：一次采集两组（不分层的调用方用）。 */
void Sensor_Collect(void);

#endif
